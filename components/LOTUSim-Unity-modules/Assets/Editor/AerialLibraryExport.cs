        static bool Finite(Vector3 vector) => !(float.IsNaN(vector.x)||float.IsInfinity(vector.x)||
            float.IsNaN(vector.y)||float.IsInfinity(vector.y)||float.IsNaN(vector.z)||float.IsInfinity(vector.z));

        static void Validate(GameObject root,string name)
        {
            var renderers=root.GetComponentsInChildren<MeshRenderer>();
            if(renderers.Length==0) throw new InvalidOperationException("No visible geometry for "+name);
            foreach(var renderer in renderers)
            {
                var mesh=renderer.GetComponent<MeshFilter>().sharedMesh;
                if(mesh==null || mesh.vertexCount==0 || mesh.uv.Length!=mesh.vertexCount || mesh.normals.Length!=mesh.vertexCount || mesh.tangents.Length!=mesh.vertexCount)
                    throw new InvalidOperationException("Invalid vertex attributes: "+name+" / "+renderer.name);
                if(mesh.vertices.Any(v=>!Finite(v)) || mesh.normals.Any(v=>!Finite(v))) throw new InvalidOperationException("Non-finite geometry.");
                if(mesh.triangles.Any(i=>i<0 || i>=mesh.vertexCount)) throw new InvalidOperationException("Invalid triangle index.");
                if(renderer.sharedMaterials.Any(m=>m==null || m.shader.name!="HDRP/Lit")) throw new InvalidOperationException("Missing HDRP material.");
            }
            if(root.GetComponentsInChildren<Rigidbody>().Length!=0) throw new InvalidOperationException("Unexpected flight physics component.");
        }

        static ModelInfo Info(GameObject prefab,string name,int classId)
        {
            var renderers=prefab.GetComponentsInChildren<MeshRenderer>();
            var bounds=new Bounds();bool first=true;int triangles=0;
            foreach(var renderer in renderers)
            {
                var mesh=renderer.GetComponent<MeshFilter>().sharedMesh;
                var matrix=prefab.transform.worldToLocalMatrix*renderer.transform.localToWorldMatrix;
                foreach(var vertex in mesh.vertices) {
                    var position=matrix.MultiplyPoint3x4(vertex);
                    if(first) {bounds=new Bounds(position,Vector3.zero);first=false;} else bounds.Encapsulate(position);
                }
                triangles+=mesh.triangles.Length/3;
            }
            return new ModelInfo{model=name,category=name=="seagull"?"bird":name=="small_drone"?"drone":name,
                address=name,prefab="Assets/Prefabs/"+name+".prefab",classId=classId,triangles=triangles,renderers=renderers.Length,
                minimum=bounds.min,maximum=bounds.max,sizeMetres=bounds.size};
        }

        static void WriteMetadata(GameObject prefab,string name,int classId)
        {
            string directory="artifacts/aerial-library";Directory.CreateDirectory(directory);
            string json=JsonUtility.ToJson(Info(prefab,name,classId),true);
            File.WriteAllText(directory+"/"+name+"-validation.json",json);
            File.WriteAllText(LibraryPath+"/"+name+"/model-info.json",json);
        }

        static string Number(float value) => value.ToString("G9",CultureInfo.InvariantCulture);
        static string XYZ(Vector3 p) => Number(p.x)+" "+Number(p.y)+" "+Number(p.z);

        static void ExportLotusim(GameObject prefab,string name,int classId)
        {
            string models=Path.GetFullPath(Path.Combine(Application.dataPath,"../../LOTUSim/assets/models"));
            if(!Directory.Exists(models)) {
                Debug.LogWarning("[AerialLibrary] LOTUSim sibling repository not found; Unity prefab remains available: "+name);return;
            }
            string directory=Path.Combine(models,name),marker=Path.Combine(directory,"aerial-library-origin.txt");
            if(Directory.Exists(directory) && !File.Exists(marker))
                throw new IOException("Refusing to overwrite a pre-existing LOTUSim model: "+directory);
            Directory.CreateDirectory(Path.Combine(directory,"meshes"));Directory.CreateDirectory(Path.Combine(directory,"textures"));
            File.WriteAllText(marker,"Original procedural visual model generated by LOTUSim.EditorTools.AerialLibraryBuilder.\n");
            var obj=new StringBuilder("# Original LOTUSim aerial visual asset. Metres; Gazebo Z-up.\nmtllib "+name+".mtl\n");
            var mtl=new StringBuilder();int offset=1;
            foreach(var renderer in prefab.GetComponentsInChildren<MeshRenderer>())
            {
                var mesh=renderer.GetComponent<MeshFilter>().sharedMesh;var material=renderer.sharedMaterial;
                var matrix=prefab.transform.worldToLocalMatrix*renderer.transform.localToWorldMatrix;
                var normalMatrix=matrix.inverse.transpose;
                obj.AppendLine("o "+renderer.name);
                foreach(var vertex in mesh.vertices) {
                    var p=matrix.MultiplyPoint3x4(vertex);obj.AppendLine("v "+XYZ(new Vector3(p.x,p.z,p.y)));
                }
                foreach(var tex in mesh.uv) obj.AppendLine("vt "+Number(tex.x)+" "+Number(tex.y));
                foreach(var normal in mesh.normals) {
                    var n=normalMatrix.MultiplyVector(normal).normalized;obj.AppendLine("vn "+XYZ(new Vector3(n.x,n.z,n.y)));
                }
                obj.AppendLine("usemtl "+material.name);
                var indices=mesh.triangles;
                // The current GzPoseToUnityPose adapter swaps Y/Z: determinant -1, so reverse triangle winding.
                for(int i=0;i<indices.Length;i+=3) {
                    int a=indices[i]+offset,b=indices[i+2]+offset,c=indices[i+1]+offset;
                    obj.AppendLine("f "+a+"/"+a+"/"+a+" "+b+"/"+b+"/"+b+" "+c+"/"+c+"/"+c);
                }
                offset+=mesh.vertexCount;
                Color color=material.GetColor("_BaseColor");
                mtl.AppendLine("newmtl "+material.name);mtl.AppendLine("Ka "+XYZ(new Vector3(color.r,color.g,color.b)));
                mtl.AppendLine("Kd "+XYZ(new Vector3(color.r,color.g,color.b)));
                mtl.AppendLine("Ks 0.10 0.10 0.10\nNs 70\nd 1\nillum 2");
                var albedo=material.GetTexture("_BaseColorMap");
                string texturePath=albedo==null?null:AssetDatabase.GetAssetPath(albedo);
                if(!string.IsNullOrEmpty(texturePath)) {
                    string file=Path.GetFileName(texturePath);File.Copy(texturePath,Path.Combine(directory,"textures",file),true);
                    mtl.AppendLine("map_Kd ../textures/"+file);
                }
            }
            File.WriteAllText(Path.Combine(directory,"meshes",name+".obj"),obj.ToString());
            File.WriteAllText(Path.Combine(directory,"meshes",name+".mtl"),mtl.ToString());
            File.WriteAllText(Path.Combine(directory,"model.config"),"<?xml version=\"1.0\"?>\n<model><name>"+name+
                "</name><version>1.0</version><sdf version=\"1.10\">model.sdf</sdf><description>Original visual-only "+name+
                " model; matching Unity prefab; no flight dynamics.</description></model>\n");
            File.WriteAllText(Path.Combine(directory,"model.sdf"),"<?xml version=\"1.0\"?>\n<sdf version=\"1.10\"><model name=\""+name+"\">\n"+
                "  <static>true</static><link name=\"body\"><visual name=\"appearance\"><geometry><mesh><uri>model://"+name+"/meshes/"+name+
                ".obj</uri></mesh></geometry></visual></link>\n"+
                "  <plugin filename=\"gz-sim-label-system\" name=\"gz::sim::systems::Label\"><label>"+classId+"</label></plugin>\n"+
                "</model></sdf>\n");
            File.WriteAllText(Path.Combine(directory,"model-info.json"),JsonUtility.ToJson(Info(prefab,name,classId),true));
            Debug.Log("[AerialLibrary] Matching Gazebo mesh exported: "+directory);
        }

        [MenuItem("LOTUSim/Models/Preview aerial library")]
        public static void PreviewAll()
        {
            foreach(string name in Names) {
                var prefab=AssetDatabase.LoadAssetAtPath<GameObject>("Assets/Prefabs/"+name+".prefab");
                if(prefab!=null) QueuePreview(prefab,name);
            }
        }

        static void QueuePreview(GameObject prefab,string name)
        {
            int tries=0;bool triedLarge=false;EditorApplication.CallbackFunction update=null;
            update=()=>{
                if(EditorApplication.isCompiling || EditorApplication.isPlayingOrWillChangePlaymode) return;
                if(!triedLarge) {
                    triedLarge=true;UnityEditor.Editor inspector=null;Texture2D texture=null;
                    try {
                        inspector=UnityEditor.Editor.CreateEditor(prefab);texture=inspector.RenderStaticPreview("Assets/Prefabs/"+name+".prefab",null,768,768);
                        if(texture!=null && texture.width>=512) SavePreview(texture,name+"-large");
                    }
                    catch(Exception exception) { Debug.LogWarning("[AerialLibrary] Optional large preview: "+exception.Message); }
                    finally { if(texture!=null) Object.DestroyImmediate(texture);if(inspector!=null) Object.DestroyImmediate(inspector); }
                }
                var preview=AssetPreview.GetAssetPreview(prefab);
                if(preview!=null) {SavePreview(preview,name);EditorApplication.update-=update;}
                else if(++tries>1000) EditorApplication.update-=update;
            };
            EditorApplication.update+=update;
        }

        static void SavePreview(Texture2D texture,string name)
        {
            Directory.CreateDirectory("artifacts/aerial-library");File.WriteAllBytes("artifacts/aerial-library/"+name+".png",texture.EncodeToPNG());
        }
