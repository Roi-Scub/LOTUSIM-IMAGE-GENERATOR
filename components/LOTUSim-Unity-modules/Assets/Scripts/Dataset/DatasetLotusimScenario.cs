using System;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using UnityEngine;

namespace Lotusim.Dataset
{
    // Offline scenario authoring only. Runtime motion is evaluated in LOTUSim.
    public static class DatasetLotusimScenario
    {
        [Serializable] sealed class LegacyEncounter
        {
            public string instance,category,modelName;public int trackId,classIndex;public float startSeconds,endSeconds,centerSeconds,distanceRequestedM,altitudeM;public Vector3 centerPosition,velocity;public float phase;
            public LegacyEncounter(DatasetEncounter e){instance=e.instance;category=e.category;modelName=e.modelName;trackId=e.trackId;classIndex=e.classIndex;startSeconds=e.startSeconds;endSeconds=e.endSeconds;centerSeconds=e.centerSeconds;distanceRequestedM=e.distanceRequestedM;altitudeM=e.altitudeM;centerPosition=e.centerPosition;velocity=e.velocity;phase=e.phase;}
        }
        // Preserve existing scenario hashes: adding optional traffic metadata
        // must not invalidate previously exported non-traffic campaigns.
        [Serializable] sealed class LegacyPlan
        {
            public string schema,motionSource,northAxis,eastAxis;public int seed,maxActive;
            public LegacyEncounter[] events;public DatasetSeaPreset sea;public DatasetLightPreset light;
            public DatasetLightingPhase[] lightingPhases;public DatasetSeaEvolution seaEvolution;
            public LegacyPlan(DatasetSequencePlan p){schema=p.schema;motionSource=p.motionSource;northAxis=p.northAxis;eastAxis=p.eastAxis;seed=p.seed;maxActive=p.maxActive;events=Array.ConvertAll(p.events,e=>new LegacyEncounter(e));sea=p.sea;light=p.light;lightingPhases=p.lightingPhases;seaEvolution=p.seaEvolution;}
        }
        public const string Name="MaritimeRandomLotusim",Observer="ObserverBoat",ObserverModel="fremm_observer";
        public static string PlanId(DatasetSequenceConfig config,DatasetSequencePlan plan)
        {
            string value=(plan.traffic==null&&plan.manual==null?JsonUtility.ToJson(new LegacyPlan(plan)):JsonUtility.ToJson(plan))+"|"+config.simulationFps+"|"+config.SimulationFrames+"|"+
                V(config.origin)+"|"+F(config.routeHeadingDeg)+"|"+F(config.observerSpeedMps)+"|"+
                ObserverModel+"|"+F(config.observerHeightM)+"|"+V(config.observerHullHalfExtentsM)+"|"+F(config.observerTurnDeg)+"|"+config.observerDeckCamera+"|"+V(config.observerDeckOffsetM)+"|"+
                string.Join(",",Array.ConvertAll(config.classes,c=>c.prefab==null?"missing":c.prefab.name));
            using(var sha=SHA256.Create()) return BitConverter.ToString(sha.ComputeHash(Encoding.UTF8.GetBytes(value))).Replace("-","").ToLowerInvariant();
        }
        public static string Yaml(DatasetSequenceConfig config,DatasetSequencePlan plan)
        {
            config.Validate();
            var text=new StringBuilder("# Generated by LOTUSim Unity Dataset; regenerate with menu 8 after changing the configuration.\n");
            text.Append("name: "+config.ScenarioName+"\ndescription: Stepped ENU kinematic multi-object dataset; no flight or wave dynamics in Gazebo.\n");
            text.Append("reference_position: {latitude: 1.2421, longitude: 103.7198, altitude: 0}\ndataset_sequence:\n");
            text.Append("  plan_id: "+PlanId(config,plan)+"\n  observer: "+Observer+"\n  fps: "+config.simulationFps+"\n  frames: "+config.SimulationFrames+"\n");
            if(plan.lightingPhases!=null) {
                text.Append("# Render-only schedule: applied by Unity at source frames, not by Gazebo lighting.\nunity_render_lighting:\n");
                foreach(var phase in plan.lightingPhases) {
                    var light=phase.light;
                    text.Append("  - start_frame: "+phase.startFrame+"\n    end_frame: "+phase.endFrame+"\n    time_of_day: '"+phase.timeOfDay+"'\n");
                    text.Append("    preset: '"+light.name.Replace("'","''")+"'\n    illuminant: '"+light.illuminant.Replace("'","''")+"'\n    exposure_ev100: "+F(light.exposureEV100)+"\n    intensity_lux: "+F(light.intensityLux)+"\n");
                }
            }
            text.Append("# HDRP render-only sea; no Gazebo wave dynamics are claimed.\nunity_render_sea:\n  preset: "+plan.sea.name+"\n  wind_kmh: "+F(plan.sea.windKmh)+"\n  band0: "+F(plan.sea.band0)+"\n  band1: "+F(plan.sea.band1)+"\n  patch_size_m: "+F(plan.sea.patchSizeM)+"\n");
            if(plan.seaEvolution!=null&&plan.seaEvolution.enabled) text.Append("  evolving: true\n  period_seconds: "+F(plan.seaEvolution.periodSeconds)+"\n  wind_range_kmh: ["+F(plan.seaEvolution.minWindKmh)+", "+F(plan.seaEvolution.maxWindKmh)+"]\n");
            text.Append("agents:\n");
            float duration=config.SimulationFrames/(float)config.simulationFps;
            Append(text,Observer,ObserverModel,config.origin,DatasetSequenceConfig.Bearing(config.routeHeadingDeg)*config.observerSpeedMps,0,0,duration,90-config.routeHeadingDeg,-config.observerTurnDeg/config.durationSeconds);
            foreach(var e in plan.events) {
                var c=config.classes[e.classIndex];
                string model=DatasetBoatVariants.Resolve(c,e).name;
                if(model!="buoy"&&model!="small_drone"&&model!="helicopter"&&model!="airplane"&&model!="seagull"&&Array.IndexOf(MarineVesselCatalog.Models,model)<0&&!DatasetExternalAssetCatalog.Matches(model,c.category))
                    throw new ArgumentException("No LOTUSim asset mapping for prefab: "+model);
                var placement=plan.manual==null?null:Array.Find(plan.manual.placements,p=>p.instance==e.instance);
                Append(text,e.instance,model,e.centerPosition,e.velocity,e.centerSeconds,e.startSeconds,e.endSeconds,placement==null?0:90-placement.headingDeg,-e.yawRateDegS,e.boundedTurn,e.turnStartSeconds,e.turnEndSeconds);
            }
            return text.ToString();
        }
        static void Append(StringBuilder text,string name,string model,Vector3 center,Vector3 velocity,float focus,float start,float end,float heading,float yawRate=0,bool boundedTurn=false,float turnStart=0,float turnEnd=0)
        {
            text.Append("  "+name+":\n    model: "+model+"\n    heading: "+F(heading)+"\n");
            text.Append("    render_interface: {enabled: "+(name==Observer?"false":"true")+", renderer_type: "+model+"}\n    trajectory:\n");
            text.Append("      center_enu_m: "+V(center)+"\n      velocity_enu_mps: "+V(velocity)+"\n");
            text.Append("      center_seconds: "+F(focus)+"\n      start_seconds: "+F(start)+"\n      end_seconds: "+F(end)+"\n");
            if(Mathf.Abs(yawRate)>1e-7f) text.Append("      yaw_rate_deg_s: "+F(yawRate)+"\n");
            if(boundedTurn)text.Append("      turn_start_seconds: "+F(turnStart)+"\n      turn_end_seconds: "+F(turnEnd)+"\n");
        }
        static string V(Vector3 p)=>"["+F(p.x)+", "+F(p.z)+", "+F(p.y)+"]";
        static string F(float v)=>v.ToString("R",CultureInfo.InvariantCulture);
    }
}
